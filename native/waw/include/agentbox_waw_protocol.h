#define AGENTBOX_WAW_RUN_ROOT "/run/agentbox-waw"
#define AGENTBOX_WAW_STATE_ROOT "/var/lib/agentbox-waw"

/* Native readiness is one complete network-order byte record.  Bootstrap uses
 * the original launch connection; attach uses its dedicated fixed FD. */
#define AGENTBOX_WAW_READY_MAGIC "AWR1"
#define AGENTBOX_WAW_READY_VERSION UINT8_C(1)
#define AGENTBOX_WAW_READY_STATUS_RUNNING UINT8_C(1)
#define AGENTBOX_WAW_READY_FRAME_BYTES UINT32_C(8)
#define AGENTBOX_WAW_READY_DEADLINE_MS UINT32_C(1000)
