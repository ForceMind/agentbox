#define AGENTBOX_WAW_RELAY_BUFFER_BYTES UINT32_C(65536)
#define AGENTBOX_WAW_NATIVE_MAX_OPEN_FDS UINT32_C(64)
#define AGENTBOX_WAW_NATIVE_VERSION "1"
