#define AGENTBOX_WAW_ATTACH_TMUX_EXECUTABLE_FD 3
#define AGENTBOX_WAW_LAUNCHER_CGROUP_FD 3
#define AGENTBOX_WAW_LAUNCHER_TMUX_EXECUTABLE_FD 4
